"""Writes the logo and the app icon for the web app from the drawing in direction-4/i_document.py.

Outputs, relative to the repository root:
  packages/documents/src/logo-shapes.ts    path data for the Logo component and the documents' wordmark
  apps/web/src/app/icon.svg                the browser tab icon (the slip i on Night, flat green)
  apps/web/src/app/apple-icon.svg          a 180 pixel source for apple-icon.png (gradient fold)

Run with SORA_800 pointing at a Sora ExtraBold instance (see direction-4/i_document.py).
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(HERE, '..', 'direction-4'))
import i_document as d  # noqa: E402

INK, ACC = '#010101', '#020202'

# The wordmark: draw it once with marker colours, then sort its shapes into ink and accent.
svg = d.wordmark('slip', 860, ink=INK, dark=False, flat=True, second='ink')
view_box = re.search(r'viewBox="([^"]+)"', svg).group(1)
ink_paths, acc_paths, ink_dots, acc_dots = [], [], [], []
for m in re.finditer(r'<path d="([^"]+)" fill="([^"]+)"', svg):
    (ink_paths if m.group(2) == INK else acc_paths).append(m.group(1))
for m in re.finditer(r'<circle cx="([^"]+)" cy="([^"]+)" r="([^"]+)" fill="([^"]+)"', svg):
    dot = dict(cx=float(m.group(1)), cy=float(m.group(2)), r=float(m.group(3)))
    (ink_dots if m.group(4) == INK else acc_dots).append(dot)
# draw_i paints the solid green for the fold and dot when flat, so anything not ink is accent
acc_paths = [p for p in acc_paths]
assert len(acc_paths) == 1 and len(acc_dots) == 1 and len(ink_dots) == 1, (len(acc_paths), len(acc_dots), len(ink_dots))

c = d.CONCEPTS['slip']
x0 = 0
# the slip is the second glyph drawn: n follows i, so the first i sits at x = 0
sw, f = c['sw'], 140
fold_line = dict(x1=x0 + c['lsb'] + sw, y1=d.ASC - d.H, x2=x0 + c['lsb'] + sw - f, y2=d.ASC - d.H + f)


def fmt_dot(o):
    return f"{{ cx: {o['cx']:.1f}, cy: {o['cy']:.1f}, r: {o['r']:.1f} }}"


ts = f"""// Generated by docs/design/direction-5/logo-svg.py from the drawing in docs/design/direction-4/i_document.py.
// The letters are Sora ExtraBold; the first i is the slip, its corner turned, the second i plain.

export const LOGO_VIEW_BOX = '{view_box}';

/** Every shape drawn in the text colour: the letters, both stems and the second dot. */
export const LOGO_INK = '{' '.join(ink_paths)}';
export const LOGO_INK_DOT = {fmt_dot(ink_dots[0])};

/** The turned corner of the slip and its dot, drawn in the accent. */
export const LOGO_FOLD = '{acc_paths[0]}';
export const LOGO_ACCENT_DOT = {fmt_dot(acc_dots[0])};

/** The line the fold's gradient runs along, from the outer corner to the crease. */
export const LOGO_FOLD_LINE = {{ x1: {fold_line['x1']:.1f}, y1: {fold_line['y1']:.1f}, x2: {fold_line['x2']:.1f}, y2: {fold_line['y2']:.1f} }};
"""
open(os.path.join(ROOT, 'packages/documents/src/logo-shapes.ts'), 'w').write(ts)


def icon_svg(size, flat, radius):
    """The slip i alone, white on Night, as a standalone SVG file."""
    inner = d.icon('slip', size, radius=radius, flat=flat)
    vb = re.search(r'<svg viewBox="([^"]+)"', inner).group(1)
    body = re.search(r'aria-hidden="true">(.*)</svg>', inner).group(1)
    vx, vy, vw, vh = (float(v) for v in vb.split())
    rx = vw * radius / size
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}" width="{size}" height="{size}">'
            f'<rect x="{vx:.1f}" y="{vy:.1f}" width="{vw:.1f}" height="{vh:.1f}" rx="{rx:.1f}" fill="{d.NIGHT}"/>'
            f'{body.replace("></path>", "/>").replace("></circle>", "/>").replace("></stop>", "/>")}</svg>\n')


open(os.path.join(ROOT, 'apps/web/src/app/icon.svg'), 'w').write(icon_svg(64, True, 14))
open(os.path.join(HERE, 'apple-icon.svg'), 'w').write(icon_svg(180, False, 0))
print('logo-shapes.ts, icon.svg and apple-icon.svg written')
