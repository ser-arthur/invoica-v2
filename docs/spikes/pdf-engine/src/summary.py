"""Builds out/summary.md from out/results.json: one matrix of candidate by document (pages, and PASS or the names of
the failing checks), then one row per candidate with check totals, median render time and file sizes.
Usage: python3 -I src/summary.py
"""
import json
import os
import statistics

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'out')
SHORT = {'page_size_a4': 'A4', 'headings_repeat': 'Head', 'lines_not_split': 'Lines', 'rows_read_in_order': 'Rows',
         'totals_whole': 'Totals', 'footer_text': 'Footer', 'footer_in_bottom_margin': 'FootPos',
         'footer_font_matches_body': 'FootFont', 'text_inside_margins': 'Margins', 'fonts_embedded': 'Embed', 'token_intact': 'Token'}


def main():
    res = json.load(open(os.path.join(OUT, 'results.json')))
    cold = json.load(open(os.path.join(OUT, 'cold-start.json'))) if os.path.exists(os.path.join(OUT, 'cold-start.json')) else None
    docs = list(next(iter(res.values()))['docs'].keys())
    short_doc = {d: d.split('-', 1)[0] for d in docs}
    lines = ['# Summary', '', 'Generated by `python3 -I src/summary.py` from out/results.json.', '',
             '## Candidate by document', '',
             'Each cell: page count, then PASS when every check passed, or the checks that failed. '
             'Documents: ' + ', '.join(f'{short_doc[d]} = {d}' for d in docs) + '.', '',
             '| Candidate | ' + ' | '.join(short_doc[d] for d in docs) + ' |', '|---|' + '---|' * len(docs)]
    for cand, data in res.items():
        cells = []
        for d in docs:
            r = data['docs'][d]
            fails = [SHORT[k] for k, ch in r['checks'].items() if ch['result'] == 'FAIL']
            cells.append(f"{r['pages']}p " + ('PASS' if not fails else 'FAIL: ' + ', '.join(fails)))
        lines.append(f'| {cand} | ' + ' | '.join(cells) + ' |')
    lines += ['', '## Checks with counts, summed over the nine documents', '',
              'Each cell: PASS or FAIL, then items examined of items expected, summed over all documents; a FAIL names the documents that failed. '
              'Items are: A4 pages; Head, pages that carry line rows; Lines and Rows, invoice lines; Totals, totals blocks; Footer, FootPos and FootFont, pages; '
              'Margins, words; Embed, font entries listed by pdffonts; Token, the one token in d3.', '',
              '| Candidate | ' + ' | '.join(SHORT.values()) + ' |', '|---|' + '---|' * len(SHORT)]
    for cand, data in res.items():
        cells = []
        for key in SHORT:
            chs = [(d, r['checks'][key]) for d, r in data['docs'].items() if key in r['checks']]
            ex = sum(ch['examined'] for _, ch in chs)
            exp = sum(ch['expected'] for _, ch in chs)
            failed = [short_doc[d] for d, ch in chs if ch['result'] == 'FAIL']
            cells.append(f'PASS {ex}/{exp}' if not failed else f'FAIL {ex}/{exp} ({", ".join(failed)})')
        lines.append(f'| {cand} | ' + ' | '.join(cells) + ' |')
    lines += ['', '## Totals per candidate', '',
              'Checks: individual check results over all nine documents (examined counts are in out/results.md). '
              'Render time: median over the nine documents of each document\'s median of three warm runs. '
              'Vivliostyle runs are cold (the CLI starts its own browser each time).', '',
              '| Candidate | Checks passed | Documents with every check passed | Render ms, median (range of per-document medians) | File size KB (range) | Boundary exercised (d7a, d7b) |',
              '|---|---|---|---|---|---|']
    for cand, data in res.items():
        checks = [ch for r in data['docs'].values() for ch in r['checks'].values()]
        passed = sum(1 for ch in checks if ch['result'] == 'PASS')
        clean = sum(1 for r in data['docs'].values() if all(ch['result'] == 'PASS' for ch in r['checks'].values()))
        ms = [r['median_ms'] for r in data['docs'].values()]
        kb = [r['bytes'] / 1024 for r in data['docs'].values()]
        ex = [data['docs'][d].get('boundary_exercised') for d in docs if 'boundary' in d]
        lines.append(f'| {cand} | {passed} of {len(checks)} | {clean} of {len(docs)} | {statistics.median(ms):.0f} ({min(ms)} to {max(ms)}) | '
                     f'{min(kb):.0f} to {max(kb):.0f} | {", ".join("yes" if e else "no" for e in ex)} |')
    if cold:
        lines += ['', f"Cold start, measured by src/cold-start.js: Chromium launch, render d1 and close took {cold['chromiumLaunchToPdfMs']} ms "
                      f"(median {cold['chromiumMedianMs']} ms); react-pdf in a fresh Node process took {cold['reactPdfFreshProcessMs']} ms "
                      f"(median {cold['reactPdfMedianMs']} ms)."]
    open(os.path.join(OUT, 'summary.md'), 'w').write('\n'.join(lines) + '\n')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
